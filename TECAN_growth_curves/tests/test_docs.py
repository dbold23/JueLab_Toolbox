# ---------------------------------------------------------------------------
# One benchmark summary, one set of numbers
# ---------------------------------------------------------------------------
#
# The repository used to state three different confusion matrices for the same
# 480 curves: validation_sum.md (326/79/56/19, dated, regenerated by nothing),
# the generated VALIDATION_SUMMARY.md (319/100/35/26) and PIPELINE_METHODOLOGY
# (87.3 % with no matrix at all).  Nothing compared them.  These tests make the
# published report.json the single source and fail on any file that contradicts
# it.

import json                                                        # noqa: E402

SYNTH_OUTPUT = ROOT / "synthetic_data" / "output"
BENCH_V2_REPORT = ROOT / "synthetic_data" / "benchmark" / "v2" / "report.json"

#: Places allowed to state a matrix that is not the current one, because their
#: whole purpose is to state a historical one and they say so:
#:   * benchmark/v1/ is the frozen pre-rebuild snapshot (its README and
#:     HEADLINE.json label it as such);
#:   * the ledger is the before/after account of the rebuild;
#:   * results/tables/ holds generated artefacts of the REAL-plate analysis and
#:     is out of scope for the synthetic benchmark (and out of bounds for this
#:     work: regenerating it is a pipeline run, not a doc edit).  Its
#:     pipeline_methodology.md still quotes the pre-rebuild 84.4 %.
HISTORICAL_PATHS = (
    "synthetic_data/benchmark/v1/",
    "docs/BENCHMARK_LEDGER.md",
    "results/tables/",
)

CONFUSION_RE = re.compile(r"(\d+)\s*\((TP|TN|FP|FN)\)")


def _is_historical(path: Path) -> bool:
    rel = path.relative_to(ROOT).as_posix()
    return any(rel.startswith(prefix) or rel == prefix.rstrip("/")
               for prefix in HISTORICAL_PATHS)


def _published_matrices():
    """Every confusion matrix the current report legitimately states."""
    report = json.loads(BENCH_V2_REPORT.read_text(encoding="utf-8"))
    blocks = [report["classification"]]
    for extra in ("core32",):
        if report["classification"].get(extra):
            blocks.append(report["classification"][extra])
    for extra in ("preprocessing_blind",):
        if report.get("truncation", {}).get(extra, {}).get("confusion_matrix"):
            blocks.append(report["truncation"][extra])
    matrices = []
    for block in blocks:
        cm = block["confusion_matrix"]
        matrices.append({"TP": cm["true_positives"], "TN": cm["true_negatives"],
                         "FP": cm["false_positives"], "FN": cm["false_negatives"]})
    return report, matrices


def _markdown_files():
    for path in sorted(ROOT.rglob("*.md")):
        rel = path.relative_to(ROOT).as_posix()
        if rel.startswith(".git/") or "/node_modules/" in rel:
            continue
        yield path


@pytest.mark.skipif(not BENCH_V2_REPORT.exists(),
                    reason="no published benchmark report in this tree")
def test_no_orphan_validation_summary():
    """One generated summary, and it agrees with report.json.

    Four assertions, from WP8's acceptance list:

    1. at most one generated summary exists under synthetic_data/output/ (it is
       a build artefact, so a fresh checkout legitimately has none);
    2. its accuracy, precision and recall match report.json to three decimals;
    3. no file in the repository states a validation confusion matrix that
       disagrees with report.json, outside the directories whose declared job
       is to state a historical one;
    4. no JSON under synthetic_data/output/ carries the legacy TP/TN/FP/FN
       keys, which is how two files came to state two matrices for one run.
    """
    report, matrices = _published_matrices()

    # (1) every summary under the output tree is machine generated, and there
    # is at most one per directory -- one per benchmark run, never a second
    # hand-kept copy beside it.  A run directory per truncation mode is legal
    # and each renders its own; what is not legal is a summary that no run
    # produced.
    summaries = sorted(SYNTH_OUTPUT.rglob("VALIDATION_SUMMARY.md")) \
        if SYNTH_OUTPUT.exists() else []
    parents = [p.parent for p in summaries]
    assert len(set(parents)) == len(parents), 'two summaries in one directory'

    for summary in summaries:
        text = summary.read_text(encoding="utf-8")
        assert "validation_summary.py" in text, (
            f'{summary.relative_to(ROOT)} is not machine generated')

        # (2) its headline agrees, to three decimals, with the report it names
        source = re.search(r"from `([^`]*report\.json)`", text)
        assert source, f'{summary.relative_to(ROOT)} does not name its report'
        source_path = ROOT / source.group(1)
        if not source_path.exists():
            continue                     # a cleaned run directory; nothing to compare
        rendered = json.loads(source_path.read_text(encoding="utf-8"))["classification"]

        found = {label: int(value) for value, label in CONFUSION_RE.findall(text)}
        assert set(found) == {"TP", "TN", "FP", "FN"}, found
        cm = rendered["confusion_matrix"]
        assert found == {"TP": cm["true_positives"], "TN": cm["true_negatives"],
                         "FP": cm["false_positives"], "FN": cm["false_negatives"]}, (
            f'{summary.relative_to(ROOT)} states {found}, its report states {cm}')
        tp, tn = found["TP"], found["TN"]
        fp, fn = found["FP"], found["FN"]
        assert round((tp + tn) / (tp + tn + fp + fn), 3) == round(
            rendered["accuracy"], 3)
        assert round(tp / (tp + fp), 3) == round(rendered["precision"], 3)
        assert round(tp / (tp + fn), 3) == round(rendered["recall"], 3)

    # (3) nothing else states a contradicting matrix
    offenders = []
    for path in _markdown_files():
        if _is_historical(path) or path in summaries:
            continue
        found = {}
        for value, label in CONFUSION_RE.findall(path.read_text(encoding="utf-8")):
            found[label] = int(value)
        if len(found) == 4 and found not in matrices:
            offenders.append(f'{path.relative_to(ROOT)}: {found}')
    assert not offenders, (
        'file(s) state a validation confusion matrix that report.json does not:\n'
        + '\n'.join(offenders))

    # (4) no legacy TP/TN/FP/FN keys in the output tree's JSON
    legacy = {"TP", "TN", "FP", "FN", "true_positives_legacy"}
    bad_keys = []
    for path in sorted(SYNTH_OUTPUT.rglob("*.json")) if SYNTH_OUTPUT.exists() else []:
        try:
            payload = json.loads(path.read_text(encoding="utf-8"))
        except (ValueError, UnicodeDecodeError):
            continue

        stack = [payload]
        while stack:
            node = stack.pop()
            if isinstance(node, dict):
                hit = legacy & set(node)
                if hit:
                    bad_keys.append(f'{path.relative_to(ROOT)}: {sorted(hit)}')
                stack.extend(node.values())
            elif isinstance(node, list):
                stack.extend(node)
    assert not bad_keys, ('legacy confusion-matrix keys under '
                          'synthetic_data/output/:\n' + '\n'.join(bad_keys))


@pytest.mark.skipif(not (ROOT / "docs" / "BENCHMARK_LEDGER.md").exists(),
                    reason="no benchmark ledger in this tree")
def test_ledger_commands_name_paths_that_exist():
    """Every repo path a ledger command reads is in the tree.

    The ledger is the only account of how the published numbers moved, and it
    is worth nothing if its commands cannot be run on a fresh checkout.  Paths
    under a run directory or /tmp are skipped: they are generated on demand and
    the ledger says so.
    """
    text = (ROOT / "docs" / "BENCHMARK_LEDGER.md").read_text(encoding="utf-8")
    blocks = re.findall(r"```(?:bash|sh)\n(.*?)```", text, flags=re.S)
    assert blocks, "the ledger states no runnable command"

    generated_prefixes = ("synthetic_data/output/comprehensive_test/validation",
                          "results/", "models/", "/tmp")
    missing = []
    for block in blocks:
        # A block may `cd` first; resolve its paths from there as well.
        roots = [ROOT]
        for target in re.findall(r"cd\s+([A-Za-z0-9_./-]+)", block):
            if (ROOT / target).is_dir():
                roots.append(ROOT / target)
        for token in re.findall(
                r"(?<![\w/.-])((?:synthetic_data|scripts|docs|tests|data|app|"
                r"tecan_growth)/[A-Za-z0-9_./*-]+)", block):
            token = token.rstrip('.,;:)"\'')
            if token.startswith(generated_prefixes) or '*' in token:
                continue
            if not any((root / token).exists() for root in roots):
                missing.append(token)
    assert not missing, (
        'the ledger runs commands against missing paths: ' + ', '.join(sorted(set(missing))))
