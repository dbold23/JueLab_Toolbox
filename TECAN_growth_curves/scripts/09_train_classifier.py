def _good_class_index(model) -> int:
    """Column of predict_proba that holds P(GOOD)."""
    classes = getattr(model, 'classes_', None)
    if classes is None and hasattr(model, 'named_steps'):
        classes = getattr(model.named_steps.get('clf', None), 'classes_', None)
    try:
        return list(classes).index(1)
    except (TypeError, ValueError):
        return 1


def score_postfit_on_audit(model, feature_names, merged: pd.DataFrame) -> Optional[dict]:
    """Post-fit metrics for one model on the audited real curves.

    ``feature_names`` is the model's OWN feature list, so a previously shipped
    model (whose list still carries the metadata columns) and a freshly trained
    one can be scored on the same rows and compared.
    """
    if len(merged) == 0:
        return None
    fitted = merged[merged['fit_attempted']].reset_index(drop=True)
    if len(fitted) == 0:
        return None
    X, y_fit = prepare_postfit_features(fitted, feature_names=feature_names)
    X = clean_feature_matrix(X)
    probs = model.predict_proba(X[list(feature_names)])[:, _good_class_index(model)]
    y_pred = (probs >= 0.5).astype(int)
    cm = confusion_matrix(y_fit, y_pred, labels=[0, 1])
    return {
        'n_curves': int(len(merged)),
        'n_postfit_curves': int(len(fitted)),
        'n_features': len(list(feature_names)),
        'accuracy': float(accuracy_score(y_fit, y_pred)),
        'precision': float(precision_score(y_fit, y_pred, zero_division=0)),
        'recall': float(recall_score(y_fit, y_pred, zero_division=0)),
        'f1': float(f1_score(y_fit, y_pred, zero_division=0)),
        'specificity': float(specificity_score(y_fit, y_pred)),
        'confusion_matrix': {
            'true_good_pred_good': int(cm[1, 1]), 'true_good_pred_bad': int(cm[1, 0]),
            'true_bad_pred_good': int(cm[0, 1]), 'true_bad_pred_bad': int(cm[0, 0]),
        },
    }


def score_shipped_model(models_dir, merged: pd.DataFrame) -> Optional[dict]:
    """Score the model currently in ``models_dir`` on the audited real curves.

    This is the "before" half of the before/after pair the retrain is judged on:
    the shipped model is loaded with its own feature_config.json feature list,
    so a feature-list change does not silently make the two numbers
    incomparable.
    """
    models_dir = Path(models_dir)
    model_path = models_dir / 'postfit_classifier.joblib'
    config_path = models_dir / 'feature_config.json'
    if not (model_path.exists() and config_path.exists()) or len(merged) == 0:
        return None
    try:
        cfg = json.loads(config_path.read_text())
        names = cfg.get('postfit_feature_names')
        if not names:
            return None
        model = joblib.load(model_path)
        summary = score_postfit_on_audit(model, names, merged)
    except Exception as exc:                       # noqa: BLE001 - report, never fail the run
        return {'error': f'{exc.__class__.__name__}: {exc}'}
    if summary is None:
        return None
    summary['model_path'] = str(model_path)
    summary['feature_names'] = list(names)
    summary['training_date'] = cfg.get('training_date')
    summary['truncation_mode'] = cfg.get('truncation_mode')
    return summary


def validate_on_real_data(model, feature_names, audit_csv, results_dir,
                          prefit_model=None):
    """Evaluate the trained models on the manual real-data audit.

    The audit set is an EXTERNAL test set: it is never part of the training
    frame, so these are out-of-sample numbers on real plates. Labels come from
    load_real_audit_data (audited verdict, flipped where the auditor said the
    pipeline was wrong).
    """
    merged = load_real_audit_data(audit_csv, results_dir)

    if len(merged) == 0:
        print("Warning: No real data results found for validation")
        return None

    y_true = merged['label'].values
    n_good = int(y_true.sum())
    n_bad = int((y_true == 0).sum())
    print(f"\nReal data: {len(merged)} curves ({n_good} GOOD, {n_bad} BAD by audit)")

    summary = {'n_curves': int(len(merged)), 'n_good': n_good, 'n_bad': n_bad}

    # --- Pre-fit gate validation ---
    if prefit_model is not None:
        print("\n  Pre-fit gate (on raw features from CSV — approximate):")
        X_pre, _ = _prepare_prefit_from_csv(merged)
        X_pre = clean_feature_matrix(X_pre)

        probs_pre = prefit_model.predict_proba(X_pre[PREFIT_FEATURES])[:, 1]
        prefit_rejects = {}
        for thresh in [0.05, 0.10, 0.20]:
            reject = probs_pre <= thresh
            n_reject = int(reject.sum())
            false_reject = int((y_true[reject] == 1).sum()) if n_reject > 0 else 0
            true_reject = int((y_true[reject] == 0).sum()) if n_reject > 0 else 0
            prefit_rejects[f'{thresh:.2f}'] = {
                'n_reject': n_reject,
                'true_bad': true_reject,
                'false_rejects': false_reject,
            }
            print(f"    threshold {thresh:.2f}: reject {n_reject}/{len(y_true)} "
                  f"({true_reject} true BAD, {false_reject} false rejects)")
        summary['prefit_rejects'] = prefit_rejects

    # --- Post-fit classifier validation ---
    # Only curves that actually reached a Gompertz fit: the post-fit classifier
    # never sees the others at inference either.
    fit_mask = merged['fit_attempted'].values
    n_unfitted = int((~fit_mask).sum())
    if n_unfitted:
        print(f"\n  {n_unfitted} curves never reached a fit "
              f"(rejected earlier); post-fit metrics cover the remaining "
              f"{int(fit_mask.sum())}")

    fitted = merged[fit_mask].reset_index(drop=True)
    summary['n_postfit_curves'] = int(len(fitted))
    if len(fitted) == 0:
        return summary

    X, y_fit = prepare_postfit_features(fitted)
    X = clean_feature_matrix(X)

    probs = model.predict_proba(X[feature_names])[:, 1]
    y_pred = (probs >= 0.5).astype(int)

    cm = confusion_matrix(y_fit, y_pred, labels=[0, 1])
    metrics = {
        'accuracy': float(accuracy_score(y_fit, y_pred)),
        'precision': float(precision_score(y_fit, y_pred, zero_division=0)),
        'recall': float(recall_score(y_fit, y_pred, zero_division=0)),
        'f1': float(f1_score(y_fit, y_pred, zero_division=0)),
        'specificity': float(specificity_score(y_fit, y_pred)),
    }
    summary['postfit_metrics'] = metrics

    print(f"\n  Post-fit classifier:")
    print(f"    Accuracy:    {metrics['accuracy']:.3f}")
    print(f"    Precision:   {metrics['precision']:.3f}")
    print(f"    Recall:      {metrics['recall']:.3f}")
    print(f"    F1:          {metrics['f1']:.3f}")
    print(f"    Specificity: {metrics['specificity']:.3f}")
    print(f"\n    Confusion matrix:")
    print(f"                     Predicted GOOD  Predicted BAD")
    print(f"      Actual GOOD:        {cm[1, 1]:4d}           {cm[1, 0]:4d}")
    print(f"      Actual BAD:         {cm[0, 1]:4d}           {cm[0, 0]:4d}")

    # Show misclassified strains
    wrong = np.where(y_pred != y_fit)[0]
    if len(wrong) > 0:
        strains = fitted.get('strain', fitted['strain_match']).values
        print(f"\n    Misclassified strains ({len(wrong)}):")
        for idx in wrong:
            true_label = 'GOOD' if y_fit[idx] == 1 else 'BAD'
            pred_label = 'GOOD' if y_pred[idx] == 1 else 'BAD'
            print(f"      {strains[idx]}: true={true_label}, pred={pred_label} "
                  f"(p={probs[idx]:.3f})")

    return summary


