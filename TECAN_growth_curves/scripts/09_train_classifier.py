def validate_on_real_data(model, feature_names, audit_csv, results_dir,
                          prefit_model=None):
    """Evaluate the trained models on the manual real-data audit.

    The audit set is an EXTERNAL test set: it is never part of the training
    frame, so these are out-of-sample numbers on real plates. Labels come from
    load_real_audit_data (audited verdict, flipped where the auditor said the
    pipeline was wrong).
    """
    merged = load_real_audit_data(audit_csv, results_dir)

    if len(merged) == 0:
        print("Warning: No real data results found for validation")
        return None

    y_true = merged['label'].values
    n_good = int(y_true.sum())
    n_bad = int((y_true == 0).sum())
    print(f"\nReal data: {len(merged)} curves ({n_good} GOOD, {n_bad} BAD by audit)")

    summary = {'n_curves': int(len(merged)), 'n_good': n_good, 'n_bad': n_bad}

    # --- Pre-fit gate validation ---
    if prefit_model is not None:
        print("\n  Pre-fit gate (on raw features from CSV — approximate):")
        X_pre, _ = _prepare_prefit_from_csv(merged)
        X_pre = clean_feature_matrix(X_pre)

        probs_pre = prefit_model.predict_proba(X_pre[PREFIT_FEATURES])[:, 1]
        prefit_rejects = {}
        for thresh in [0.05, 0.10, 0.20]:
            reject = probs_pre <= thresh
            n_reject = int(reject.sum())
            false_reject = int((y_true[reject] == 1).sum()) if n_reject > 0 else 0
            true_reject = int((y_true[reject] == 0).sum()) if n_reject > 0 else 0
            prefit_rejects[f'{thresh:.2f}'] = {
                'n_reject': n_reject,
                'true_bad': true_reject,
                'false_rejects': false_reject,
            }
            print(f"    threshold {thresh:.2f}: reject {n_reject}/{len(y_true)} "
                  f"({true_reject} true BAD, {false_reject} false rejects)")
        summary['prefit_rejects'] = prefit_rejects

    # --- Post-fit classifier validation ---
    # Only curves that actually reached a Gompertz fit: the post-fit classifier
    # never sees the others at inference either.
    fit_mask = merged['fit_attempted'].values
    n_unfitted = int((~fit_mask).sum())
    if n_unfitted:
        print(f"\n  {n_unfitted} curves never reached a fit "
              f"(rejected earlier); post-fit metrics cover the remaining "
              f"{int(fit_mask.sum())}")

    fitted = merged[fit_mask].reset_index(drop=True)
    summary['n_postfit_curves'] = int(len(fitted))
    if len(fitted) == 0:
        return summary

    X, y_fit = prepare_postfit_features(fitted)
    X = clean_feature_matrix(X)

    probs = model.predict_proba(X[feature_names])[:, 1]
    y_pred = (probs >= 0.5).astype(int)

    cm = confusion_matrix(y_fit, y_pred, labels=[0, 1])
    metrics = {
        'accuracy': float(accuracy_score(y_fit, y_pred)),
        'precision': float(precision_score(y_fit, y_pred, zero_division=0)),
        'recall': float(recall_score(y_fit, y_pred, zero_division=0)),
        'f1': float(f1_score(y_fit, y_pred, zero_division=0)),
        'specificity': float(specificity_score(y_fit, y_pred)),
    }
    summary['postfit_metrics'] = metrics

    print(f"\n  Post-fit classifier:")
    print(f"    Accuracy:    {metrics['accuracy']:.3f}")
    print(f"    Precision:   {metrics['precision']:.3f}")
    print(f"    Recall:      {metrics['recall']:.3f}")
    print(f"    F1:          {metrics['f1']:.3f}")
    print(f"    Specificity: {metrics['specificity']:.3f}")
    print(f"\n    Confusion matrix:")
    print(f"                     Predicted GOOD  Predicted BAD")
    print(f"      Actual GOOD:        {cm[1, 1]:4d}           {cm[1, 0]:4d}")
    print(f"      Actual BAD:         {cm[0, 1]:4d}           {cm[0, 0]:4d}")

    # Show misclassified strains
    wrong = np.where(y_pred != y_fit)[0]
    if len(wrong) > 0:
        strains = fitted.get('strain', fitted['strain_match']).values
        print(f"\n    Misclassified strains ({len(wrong)}):")
        for idx in wrong:
            true_label = 'GOOD' if y_fit[idx] == 1 else 'BAD'
            pred_label = 'GOOD' if y_pred[idx] == 1 else 'BAD'
            print(f"      {strains[idx]}: true={true_label}, pred={pred_label} "
                  f"(p={probs[idx]:.3f})")

    return summary


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(
        description='Train ML classifiers for growth curve quality'
    )
    parser.add_argument(
        '--ground-truth',
        default='synthetic_data/output/comprehensive_test/test_data/ground_truth.csv',
        help='Path to ground truth CSV'
    )
    parser.add_argument(
        '--processing-results',
        default=None,
        help='Path to an existing processing_results.csv to train on. By '
             'default the features are rebuilt by running the analysis script '
             'without --ml-classify (the validation run is produced WITH the '
             'ML gate, so it cannot be used as training data).'
    )
    parser.add_argument(
        '--training-features-dir',
        default=DEFAULT_TRAINING_FEATURES_DIR,
        help=f'Directory for the rebuilt (ML-gate-free) training features '
             f'(default: {DEFAULT_TRAINING_FEATURES_DIR})'
    )
    parser.add_argument(
        '--rebuild-features', action='store_true',
        help='Rebuild the training features even if they are already cached'
    )
    parser.add_argument(
        '--feature-build-arg', action='append', default=None,
        dest='feature_build_args', metavar='FLAG',
        help='Extra flag passed to 01_growth_curve_analysis.py when building '
             'training features (repeatable). The build uses config.yaml '
             'defaults, i.e. adaptive truncation, which is slow on a full '
             'synthetic set; --feature-build-arg=--no-adaptive trades fidelity '
             'with the deployed pipeline for speed.'
    )
    parser.add_argument(
        '--raw-data-dir',
        default='synthetic_data/output/comprehensive_test/test_data/DATA',
        help='Directory with raw OD CSV files for pre-fit feature extraction'
    )
    parser.add_argument(
        '--output', default='models/',
        help='Output directory for serialized models'
    )
    parser.add_argument(
        '--compare', action='store_true',
        help='Compare GBT vs RF'
    )
    parser.add_argument(
        '--validate-real', action='store_true',
        help='Also report metrics on the held-out real audit data'
    )
    parser.add_argument(
        '--audit-csv',
        default='results/tables/validation_audit.csv',
        help='Path to manual audit CSV'
    )
    parser.add_argument(
        '--results-dir',
        default='results/tables',
        help='Directory with real data processing results'
    )
    parser.add_argument(
        '--n-folds', type=int, default=5,
        help='Number of CV folds'
    )
    args = parser.parse_args()

    output_dir = Path(args.output)
    output_dir.mkdir(parents=True, exist_ok=True)

    # Load data
    print("=" * 60)
    print("LOADING TRAINING DATA")
    print("=" * 60)

    if args.processing_results:
        processing_results = Path(args.processing_results)
        features_source = 'user-supplied (--processing-results)'
        print(f"Using supplied processing results: {processing_results}")
        if results_are_ml_gated(processing_results):
            print("  WARNING: this file was produced WITH --ml-classify. Curves the")
            print("  gate rejected were never fitted, so the post-fit classifier")
            print("  would only learn 'has fit features -> GOOD'. Drop")
            print("  --processing-results to rebuild honest features.")
    else:
        processing_results = build_training_features(
            args.raw_data_dir,
            args.training_features_dir,
            force=args.rebuild_features,
            extra_args=args.feature_build_args,
        )
        features_source = 'rebuilt without --ml-classify'

    df = load_training_data(args.ground_truth, str(processing_results))
    df['source'] = 'synthetic'

    # The real audit set is an EXTERNAL TEST SET: it is deliberately NOT mixed
    # into the training frame, so real-data numbers stay out-of-sample.
    real_df = pd.DataFrame()
    if Path(args.audit_csv).exists() and Path(args.results_dir).exists():
        print("\nLoading real audit data (held out — never trained on)...")
        real_df = load_real_audit_data(args.audit_csv, args.results_dir)

    # -----------------------------------------------------------------------
    # 70/30 Stratified train/test split
    # -----------------------------------------------------------------------
    print("\n" + "=" * 60)
    print("TRAIN/TEST SPLIT (70/30 stratified, synthetic only)")
    print("=" * 60)

    train_df, test_df = train_test_split(
        df, test_size=0.3, random_state=42, stratify=df['label']
    )
    print(f"  Train: {len(train_df)} ({train_df['label'].sum()} GOOD, "
          f"{(train_df['label'] == 0).sum()} BAD)")
    print(f"  Test:  {len(test_df)} ({test_df['label'].sum()} GOOD, "
          f"{(test_df['label'] == 0).sum()} BAD)")
    if len(real_df) > 0:
        print(f"  Real audit set held out entirely: {len(real_df)} curves "
              f"(external test only)")

    # -----------------------------------------------------------------------
    # Train pre-fit gate (on train split only)
    # -----------------------------------------------------------------------
    print("\n" + "=" * 60)
    print("TRAINING PRE-FIT GATE")
    print("=" * 60)

    X_pre_train, y_pre_train = prepare_prefit_features(train_df, raw_data_dir=args.raw_data_dir)
    X_pre_test, y_pre_test = prepare_prefit_features(test_df, raw_data_dir=args.raw_data_dir)
    assert_features_present(X_pre_train, 'synthetic pre-fit training set')
    print(f"Pre-fit features: {list(X_pre_train.columns)}")
    print(f"Train: {X_pre_train.shape}, Test: {X_pre_test.shape}")

    prefit_model, prefit_metrics = train_model(X_pre_train, y_pre_train, 'hgb', args.n_folds)

    print(f"\nPre-fit gate CV results ({args.n_folds}-fold on train set):")
    for k in ['accuracy', 'precision', 'recall', 'f1', 'specificity']:
        print(f"  {k:12s}: {prefit_metrics[k]:.3f} ± {prefit_metrics[f'{k}_std']:.3f}")

    # Evaluate on held-out test set
    X_pre_test_clean = clean_feature_matrix(X_pre_test)
    probs_pre_test = prefit_model.predict_proba(X_pre_test_clean[PREFIT_FEATURES])[:, 1]
    print(f"\nPre-fit gate HELD-OUT TEST results:")
    for thresh in [0.05, 0.10, 0.20, 0.30]:
        reject_mask = probs_pre_test <= thresh
        n_reject = reject_mask.sum()
        false_reject = (y_pre_test[reject_mask] == 1).sum() if n_reject > 0 else 0
        true_reject = (y_pre_test[reject_mask] == 0).sum() if n_reject > 0 else 0
        print(f"  threshold {thresh:.2f}: reject {n_reject}/{len(y_pre_test)} "
              f"({true_reject} true BAD, {false_reject} false rejects)")

    joblib.dump(prefit_model, output_dir / 'prefit_gate.joblib')
    print(f"\nSaved pre-fit gate to {output_dir / 'prefit_gate.joblib'}")

    # -----------------------------------------------------------------------
    # Train post-fit classifier (on train split only)
    # -----------------------------------------------------------------------
    print("\n" + "=" * 60)
    print("TRAINING POST-FIT CLASSIFIER")
    print("=" * 60)

    # Only curves that actually reached a Gompertz fit carry post-fit features.
    # Training on the rest teaches the classifier "features present -> GOOD".
    train_fit_df = train_df[train_df['fit_attempted']].reset_index(drop=True)
    test_fit_df = test_df[test_df['fit_attempted']].reset_index(drop=True)
    print(f"Rows with a fit: train {len(train_fit_df)}/{len(train_df)}, "
          f"test {len(test_fit_df)}/{len(test_df)} "
          f"(unfitted rows are excluded — every post-fit feature is NaN there)")
    print(f"  Train labels: {int(train_fit_df['label'].sum())} GOOD, "
          f"{int((train_fit_df['label'] == 0).sum())} BAD")

    if train_fit_df['label'].nunique() < 2:
        print("\nERROR: the fitted training rows are all one class.")
        print("  This is what happens when the training features come from a run")
        print("  made WITH --ml-classify: the gate rejects every bad curve before")
        print("  fitting. Rebuild features with --rebuild-features (or drop")
        print("  --processing-results) so every curve is fitted.")
        sys.exit(1)

    X_post_train, y_post_train = prepare_postfit_features(train_fit_df)
    X_post_test, y_post_test = prepare_postfit_features(test_fit_df)
    assert_features_present(X_post_train, 'synthetic post-fit training set')
    print(f"Post-fit features: {list(X_post_train.columns)}")
    print(f"Train: {X_post_train.shape}, Test: {X_post_test.shape}")

    postfit_model, postfit_metrics = train_model(X_post_train, y_post_train, 'hgb', args.n_folds)

    print(f"\nPost-fit classifier CV results ({args.n_folds}-fold on train set):")
    for k in ['accuracy', 'precision', 'recall', 'f1', 'specificity']:
        print(f"  {k:12s}: {postfit_metrics[k]:.3f} ± {postfit_metrics[f'{k}_std']:.3f}")

    # Feature importance
    if 'feature_importance' in postfit_metrics:
        print("\nTop 10 features:")
        for i, (feat, imp) in enumerate(postfit_metrics['feature_importance'].items()):
            if i >= 10:
                break
            print(f"  {feat:30s}: {imp:.4f}")

    # -----------------------------------------------------------------------
    # HELD-OUT TEST SET evaluation (the honest numbers)
    # -----------------------------------------------------------------------
    print("\n" + "=" * 60)
    print("HELD-OUT TEST SET RESULTS (30% never seen during training)")
    print("=" * 60)

    X_post_test_clean = clean_feature_matrix(X_post_test)
    probs_test = postfit_model.predict_proba(X_post_test_clean[ALL_POSTFIT_FEATURES])[:, 1]
    y_pred_test = (probs_test >= 0.5).astype(int)

    print(f"\nPost-fit classifier on {len(y_post_test)} held-out curves:")
    print(f"  Accuracy:    {accuracy_score(y_post_test, y_pred_test):.3f}")
    print(f"  Precision:   {precision_score(y_post_test, y_pred_test, zero_division=0):.3f}")
    print(f"  Recall:      {recall_score(y_post_test, y_pred_test, zero_division=0):.3f}")
    print(f"  F1:          {f1_score(y_post_test, y_pred_test, zero_division=0):.3f}")
    print(f"  Specificity: {specificity_score(y_post_test, y_pred_test):.3f}")

    cm = confusion_matrix(y_post_test, y_pred_test)
    print(f"\n  Confusion matrix (held-out test):")
    print(f"                   Predicted GOOD  Predicted BAD")
    print(f"    Actual GOOD:        {cm[1,1]:4d}           {cm[1,0]:4d}")
    print(f"    Actual BAD:         {cm[0,1]:4d}           {cm[0,0]:4d}")

    # Three-class analysis on test set
    print(f"\n  Three-class analysis (held-out test):")
    for good_t, bad_t in [(0.7, 0.3), (0.6, 0.4), (0.8, 0.2)]:
        good_mask = probs_test >= good_t
        bad_mask = probs_test <= bad_t
        border_mask = ~good_mask & ~bad_mask
        y_cons = good_mask.astype(int)
        bg = (y_post_test[border_mask] == 1).sum()
        bb = (y_post_test[border_mask] == 0).sum()
        print(f"    [{bad_t:.1f}, {good_t:.1f}]: GOOD={good_mask.sum()}, "
              f"BORDERLINE={border_mask.sum()} ({bg}G+{bb}B), "
              f"BAD={bad_mask.sum()}, acc={accuracy_score(y_post_test, y_cons):.3f}")

    # Show misclassified test strains
    if 'strain' in test_fit_df.columns:
        test_strains = test_fit_df['strain'].values
    else:
        test_strains = test_fit_df.get(
            'strain_match', pd.Series(['?'] * len(test_fit_df))
        ).values
    misclassified = np.where(y_pred_test != y_post_test)[0]
    if len(misclassified) > 0:
        print(f"\n  Misclassified ({len(misclassified)}):")
        for idx in misclassified:
            true_label = 'GOOD' if y_post_test[idx] == 1 else 'BAD'
            pred_label = 'GOOD' if y_pred_test[idx] == 1 else 'BAD'
            strain = test_strains[idx] if idx < len(test_strains) else '?'
            print(f"    {strain}: true={true_label}, pred={pred_label} "
                  f"(p={probs_test[idx]:.3f})")

    # -----------------------------------------------------------------------
    # Validate on real data BEFORE retrain (uses train-split-only models)
    # -----------------------------------------------------------------------
    real_summary = None
    if args.validate_real:
        print("\n" + "=" * 60)
        print("REAL DATA: EXTERNAL TEST SET (never used for training)")
        print("=" * 60)
        real_summary = validate_on_real_data(
            postfit_model, feature_names=ALL_POSTFIT_FEATURES,
            audit_csv=args.audit_csv, results_dir=args.results_dir,
            prefit_model=prefit_model,
        )

    # -----------------------------------------------------------------------
    # Now retrain the deployed models on ALL the synthetic data (the real audit
    # set stays out: it is the external test set)
    # -----------------------------------------------------------------------
    print("\n" + "=" * 60)
    print("RETRAINING FINAL MODEL ON ALL SYNTHETIC DATA (for deployment)")
    print("=" * 60)

    fit_df = df[df['fit_attempted']].reset_index(drop=True)
    X_pre_all, y_pre_all = prepare_prefit_features(df, raw_data_dir=args.raw_data_dir)
    X_post_all, y_post_all = prepare_postfit_features(fit_df)

    X_pre_all = clean_feature_matrix(X_pre_all)
    X_post_all = clean_feature_matrix(X_post_all)

    prefit_model.fit(X_pre_all, y_pre_all)
    postfit_model.fit(X_post_all, y_post_all)

    joblib.dump(prefit_model, output_dir / 'prefit_gate.joblib')
    joblib.dump(postfit_model, output_dir / 'postfit_classifier.joblib')
    print(f"\nSaved post-fit classifier to {output_dir / 'postfit_classifier.joblib'}")

    # -----------------------------------------------------------------------
    # Compare GBT vs RF (optional)
    # -----------------------------------------------------------------------
    if args.compare:
        print("\n" + "=" * 60)
        print("MODEL COMPARISON (GBT vs RF)")
        print("=" * 60)

        rf_model, rf_metrics = train_model(X_post_all, y_post_all, 'rf', args.n_folds)
        print(f"\n{'Metric':<15s} {'GBT':>10s} {'RF':>10s}")
        print("-" * 37)
        for k in ['accuracy', 'precision', 'recall', 'f1', 'specificity']:
            print(f"  {k:<13s} {postfit_metrics[k]:>9.3f}  {rf_metrics[k]:>9.3f}")

    # -----------------------------------------------------------------------
    # Save feature config
    # -----------------------------------------------------------------------
    feature_config = {
        'prefit_feature_names': PREFIT_FEATURES,
        'postfit_feature_names': ALL_POSTFIT_FEATURES,
        'prefit_metrics': {k: v for k, v in prefit_metrics.items() if k != 'feature_importance'},
        'postfit_metrics': {k: v for k, v in postfit_metrics.items() if k != 'feature_importance'},
        'postfit_feature_importance': postfit_metrics.get('feature_importance', {}),
        'training_date': datetime.now().isoformat(),
        'trained_on': 'synthetic_only',
        'training_features': {
            'ground_truth': str(args.ground_truth),
            'processing_results': str(processing_results),
            'processing_results_source': features_source,
            'raw_data_dir': str(args.raw_data_dir),
        },
        'n_training_samples': int(len(df)),
        'n_prefit_training_samples': int(len(df)),
        'n_postfit_training_samples': int(len(fit_df)),
        'class_distribution': {
            'GOOD': int(df['label'].sum()),
            'BAD': int((~df['label'].astype(bool)).sum()),
        },
        'postfit_class_distribution': {
            'GOOD': int(fit_df['label'].sum()),
            'BAD': int((~fit_df['label'].astype(bool)).sum()),
        },
        'real_audit_holdout': {
            'n_curves': int(len(real_df)),
            'GOOD': int(real_df['label'].sum()) if len(real_df) else 0,
            'BAD': int((real_df['label'] == 0).sum()) if len(real_df) else 0,
            'used_for_training': False,
            'external_test_results': real_summary,
        },
        'model_type': 'HistGradientBoostingClassifier',
    }

    config_path = output_dir / 'feature_config.json'
    with open(config_path, 'w') as f:
        json.dump(feature_config, f, indent=2)
    print(f"\nSaved feature config to {config_path}")

    print("\n" + "=" * 60)
    print("DONE")
    print("=" * 60)


if __name__ == '__main__':
    main()
