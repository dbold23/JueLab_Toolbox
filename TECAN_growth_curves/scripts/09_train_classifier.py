#: Sidecar written next to the cached training features. It is what makes the
#: cache checkable: without it the mode a cache was built under is UNKNOWN, and
#: an unknown-mode cache is rebuilt rather than trusted (M26: the cached
#: training_features/processing_results.csv in the tree is byte-identical to the
#: first-peak validation run while config.yaml sets use_adaptive: true).
FEATURE_BUILD_SIDECAR = 'feature_build.json'

#: The mode the committed baseline was measured under, and this script's
#: default. ``truncation.use_adaptive`` in config.yaml is the *batch* default
#: for real plates; leaving the training build to inherit it is how the cache
#: silently drifted out of the published benchmark's mode.
DEFAULT_TRUNCATION_MODE = 'first_peak'

#: Command-line spelling of each mode for 01_growth_curve_analysis.py. Each is
#: spelled out in full: '--no-adaptive' alone still leaves the choice between
#: first-peak and global-max to config.yaml's truncation.use_first_peak.
TRUNCATION_MODE_FLAGS = {
    'adaptive': ['--adaptive'],
    'first_peak': ['--no-adaptive', '--first-peak'],
    'global_max': ['--no-adaptive', '--global-max'],
}

#: Which modes a hand-passed --feature-build-arg flag is compatible with.
_FLAG_MODES = {
    '--adaptive': {'adaptive'},
    '--no-adaptive': {'first_peak', 'global_max'},
    '--first-peak': {'first_peak', 'adaptive'},
    '--global-max': {'global_max', 'adaptive'},
}


def resolve_truncation_mode(
    truncation_mode: Optional[str] = None,
    extra_args: Optional[Sequence[str]] = None,
) -> str:
    """Resolve the truncation mode for a feature build, or raise on a conflict.

    ``extra_args`` are the raw flags a caller passed through with
    ``--feature-build-arg``. They may agree with the mode (``--no-adaptive``
    with ``first_peak``) but never override it silently.
    """
    mode = truncation_mode or DEFAULT_TRUNCATION_MODE
    if mode not in TRUNCATION_MODE_FLAGS:
        raise ValueError(
            f"unknown truncation mode {mode!r}; expected one of "
            f"{sorted(TRUNCATION_MODE_FLAGS)}"
        )
    for flag in (extra_args or []):
        allowed = _FLAG_MODES.get(str(flag))
        if allowed is not None and mode not in allowed:
            raise ValueError(
                f"--feature-build-arg={flag} contradicts --truncation-mode "
                f"{mode}: that flag selects {sorted(allowed)}. Drop the flag "
                f"and let --truncation-mode decide."
            )
    return mode


def _sha256_file(path) -> Optional[str]:
    try:
        return hashlib.sha256(Path(path).read_bytes()).hexdigest()
    except OSError:
        return None


def truncation_block_hash(config_path) -> Optional[str]:
    """SHA-256 of config.yaml's truncation block, or None when unreadable.

    Only the truncation block: changing a plotting option must not invalidate a
    cache, but changing PEAK_RATE_FRACTION or buffer_points must.
    """
    try:
        import yaml
        with open(config_path) as fh:
            cfg = yaml.safe_load(fh) or {}
    except Exception:
        return None
    block = cfg.get('truncation', {})
    return hashlib.sha256(
        json.dumps(block, sort_keys=True, default=str).encode()
    ).hexdigest()


def _git_describe(path) -> Dict[str, Optional[str]]:
    """Last commit touching ``path`` plus whether it is dirty in the tree."""
    out = {'git_sha': None, 'git_dirty': None}
    try:
        sha = subprocess.run(
            ['git', 'log', '-1', '--format=%H', '--', str(path)],
            cwd=str(REPO_ROOT), capture_output=True, text=True, timeout=30,
        )
        if sha.returncode == 0 and sha.stdout.strip():
            out['git_sha'] = sha.stdout.strip()
        status = subprocess.run(
            ['git', 'status', '--porcelain', '--', str(path)],
            cwd=str(REPO_ROOT), capture_output=True, text=True, timeout=30,
        )
        if status.returncode == 0:
            out['git_dirty'] = bool(status.stdout.strip())
    except (OSError, subprocess.SubprocessError):
        pass
    return out


def read_feature_build(output_dir) -> Optional[dict]:
    """Read the feature_build.json sidecar, or None when it is missing."""
    path = Path(output_dir) / FEATURE_BUILD_SIDECAR
    try:
        with open(path) as fh:
            data = json.load(fh)
    except (OSError, ValueError):
        return None
    return data if isinstance(data, dict) else None


def _run_settings_mode(output_dir) -> Optional[str]:
    """truncation_mode from the pipeline's own run_settings.json (WP9), if any."""
    try:
        with open(Path(output_dir) / 'run_settings.json') as fh:
            return (json.load(fh) or {}).get('truncation_mode')
    except (OSError, ValueError, AttributeError):
        return None


def check_feature_cache(
    output_dir,
    truncation_mode: str,
    raw_data_dir: str,
) -> tuple:
    """Decide whether a cached feature build may be reused.

    Returns ``(reusable, reason)``. The reason is printed either way, so a run
    always says which cache it took and why.
    """
    out_dir = Path(output_dir)
    results_csv = out_dir / 'processing_results.csv'
    if not results_csv.exists():
        return False, f"no cached {results_csv}"

    if results_are_ml_gated(results_csv):
        return False, (
            f"cached {results_csv} was produced WITH the ML gate: curves the "
            f"gate rejected were never fitted"
        )

    sidecar = read_feature_build(out_dir)
    # The pipeline's own sidecar (WP9) is the authority on the mode when it is
    # there; feature_build.json records what this script asked for.
    run_mode = _run_settings_mode(out_dir)
    cached_mode = (sidecar or {}).get('truncation_mode') or run_mode

    if cached_mode is None:
        return False, (
            f"cached {results_csv} has no {FEATURE_BUILD_SIDECAR} and no "
            f"run_settings.json, so the truncation mode it was built under is "
            f"UNKNOWN; rebuilding in '{truncation_mode}' mode"
        )
    if cached_mode != truncation_mode:
        return False, (
            f"cached training features were built with truncation mode "
            f"'{cached_mode}' but this run resolves to '{truncation_mode}'; "
            f"fit-quality features are not comparable across modes, rebuilding "
            f"in '{truncation_mode}' mode"
        )
    if run_mode is not None and sidecar and sidecar.get('truncation_mode') not in (None, run_mode):
        return False, (
            f"cache provenance disagrees: {FEATURE_BUILD_SIDECAR} says "
            f"'{sidecar.get('truncation_mode')}' and run_settings.json says "
            f"'{run_mode}'; rebuilding in '{truncation_mode}' mode"
        )

    cached_dir = (sidecar or {}).get('raw_data_dir')
    if cached_dir and Path(cached_dir).resolve() != Path(raw_data_dir).resolve():
        return False, (
            f"cached features were built from {cached_dir}, not {raw_data_dir}"
        )

    return True, f"cached features are '{cached_mode}' mode, matching this run"


def build_training_features(
    raw_data_dir: str,
    output_dir: str,
    force: bool = False,
    extra_args: Optional[Sequence[str]] = None,
    truncation_mode: Optional[str] = None,
    config_path: Optional[str] = None,
) -> Path:
    """Run 01_growth_curve_analysis.py WITHOUT the ML gate to get training features.

    The committed validation run is produced by the deployed pipeline, and step
    9 can be asked to run it *with* --ml-classify, i.e. by the very model being
    trained: every curve its pre-fit gate rejects then carries NaN for all fit
    features, so a classifier trained on that file only learns "has fit features
    -> GOOD". (The committed run in the tree is NOT ML-gated -- p_good is NaN on
    all 480 rows -- but nothing stops the next one from being, which is why
    ``results_are_ml_gated`` checks rather than assumes.) Training features have
    to come from a run where every curve gets the same chance to be fitted.

    The truncation mode is resolved here rather than inherited from config.yaml,
    written to a ``feature_build.json`` sidecar, and checked before a cached
    build is reused: a cache built in another mode, or with no sidecar at all,
    is rebuilt. Pass force=True to rebuild unconditionally.
    """
    mode = resolve_truncation_mode(truncation_mode, extra_args)
    out_dir = Path(output_dir)
    results_csv = out_dir / 'processing_results.csv'

    if not force:
        reusable, reason = check_feature_cache(out_dir, mode, raw_data_dir)
        if reusable:
            print(f"Reusing training features: {results_csv}")
            print(f"  ({reason}; pass --rebuild-features to regenerate)")
            return results_csv
        if results_csv.exists():
            print(f"Rebuilding training features: {reason}")

    data_dir = Path(raw_data_dir)
    if not data_dir.is_dir():
        raise FileNotFoundError(
            f"raw data directory not found: {data_dir} — pass --raw-data-dir or "
            f"--processing-results"
        )

    resolved_config = Path(config_path) if config_path else (ANALYSIS_SCRIPT.parent / 'config.yaml')

    out_dir.mkdir(parents=True, exist_ok=True)
    cmd = [
        sys.executable, str(ANALYSIS_SCRIPT), str(data_dir),
        '-o', str(out_dir), '--no-plots', '-q',
    ]
    if config_path:
        cmd += ['--config', str(config_path)]
    cmd += TRUNCATION_MODE_FLAGS[mode]
    if extra_args:
        cmd += list(extra_args)

    print(f"Building training features WITHOUT --ml-classify from {data_dir}")
    print(f"  truncation mode: {mode} (explicit — not inherited from config.yaml)")
    print(f"  $ {' '.join(cmd)}")
    if mode == 'adaptive':
        print("  Adaptive truncation re-fits every window, so a full synthetic")
        print("  set takes hours. The result is cached in the output directory;")
        print("  --truncation-mode first_peak is the committed baseline's mode.")
    subprocess.run(cmd, check=True, env={**os.environ, 'MPLBACKEND': 'Agg'})

    if not results_csv.exists():
        raise RuntimeError(f"feature build produced no {results_csv}")

    write_feature_build(
        out_dir,
        truncation_mode=mode,
        extra_args=list(extra_args or []),
        raw_data_dir=str(data_dir),
        config_path=str(resolved_config),
        results_csv=results_csv,
    )
    return results_csv


def write_feature_build(
    output_dir,
    truncation_mode: str,
    extra_args: Sequence[str],
    raw_data_dir: str,
    config_path: str,
    results_csv,
) -> Path:
    """Write the feature_build.json provenance sidecar."""
    out_dir = Path(output_dir)
    run_mode = _run_settings_mode(out_dir)
    if run_mode is not None and run_mode != truncation_mode:
        print(
            f"  WARNING: the pipeline's run_settings.json reports mode "
            f"'{run_mode}' but this build asked for '{truncation_mode}'"
        )
    sidecar = {
        'schema': 'feature_build/1',
        'truncation_mode': truncation_mode,
        'truncation_mode_source': 'explicit (--truncation-mode)',
        'pipeline_reported_truncation_mode': run_mode,
        'extra_args': list(extra_args),
        'raw_data_dir': str(Path(raw_data_dir).resolve()),
        'config_path': str(config_path),
        'config_sha256': _sha256_file(config_path),
        'truncation_block_sha256': truncation_block_hash(config_path),
        'analysis_script': str(ANALYSIS_SCRIPT),
        'analysis_script_git_sha': _git_describe(ANALYSIS_SCRIPT)['git_sha'],
        'analysis_script_git_dirty': _git_describe(ANALYSIS_SCRIPT)['git_dirty'],
        'ml_gated': bool(results_are_ml_gated(results_csv)),
        'results_csv': str(Path(results_csv).resolve()),
        'built_at': datetime.now().isoformat(),
    }
    path = out_dir / FEATURE_BUILD_SIDECAR
    with open(path, 'w') as fh:
        json.dump(sidecar, fh, indent=2)
    print(f"  Wrote {path}")
    return path


def results_are_ml_gated(processing_results_csv) -> bool:
    """True if this processing_results.csv was produced with --ml-classify.

    Such a run is not usable as training data: curves the ML gate rejected were
    never fitted, so 'has fit features' encodes the model's own verdict.
    """
    try:
        df = pd.read_csv(processing_results_csv)
    except Exception:
        return False
    for col in ('p_good', 'ml_classification'):
        if col in df.columns and df[col].notna().any():
            return True
    return False


def _as_bool(series: pd.Series) -> pd.Series:
    """Coerce a CSV-loaded truthy column to bool (handles 'True'/'False' text)."""
    if series.dtype == bool:
        return series
    return series.astype(str).str.strip().str.lower().isin({'true', '1', 'yes'})


def assert_features_present(X: pd.DataFrame, source: str) -> None:
    """Fail loudly if a feature column is entirely NaN for this data source.

    An all-NaN feature column means the merge renamed it away (or the source
    never produced it), which the model would silently read as
    source-identifying missingness — and, once clean_feature_matrix freezes it
    to 0.0, as a shipped feature that is constant in training and variable at
    inference.

    There is NO exemption. The metadata features used to be exempt here, which
    is exactly how two all-NaN columns stayed in the shipped feature lists
    through four retrains (M27); they are no longer model features, so any
    all-NaN column is now a real defect.
    """
    all_nan = [c for c in X.columns if X[c].isna().all()]
    if all_nan:
        raise ValueError(
            f"{source}: feature column(s) entirely NaN: {all_nan}. "
            f"Check that the merge is not renaming feature columns, and that "
            f"every shipped feature is one this data source actually produces."
        )


def constant_features(X: pd.DataFrame) -> List[str]:
    """Feature columns with fewer than two distinct non-missing values.

    A constant column is what sklearn's binner sees as
    ``n_bins_non_missing_ == 1``: the model cannot split on it, so shipping it
    in the feature list only creates training/serving skew.
    """
    out = []
    for col in X.columns:
        values = pd.to_numeric(X[col], errors='coerce')
        if values.replace([np.inf, -np.inf], np.nan).dropna().nunique() < 2:
            out.append(col)
    return out


def assert_features_non_constant(X: pd.DataFrame, source: str) -> List[str]:
    """Warn loudly about constant shipped features and return them."""
    constants = constant_features(X)
    if constants:
        print(f"  WARNING: {source}: feature column(s) constant in this frame: "
              f"{constants}. A constant feature cannot be split on and is "
              f"recorded in feature_config.json as constant_features.")
    return constants


def clean_feature_matrix(X: pd.DataFrame) -> pd.DataFrame:
    """Prepare a feature matrix for HistGradientBoosting.

    Replaces inf with NaN (HGB handles NaN natively) and neutralises columns
    that are entirely missing, because sklearn's binner raises on a column with
    zero distinct values. That neutralisation is a crash guard, not a licence:
    the training paths call assert_features_present() first, so an all-NaN
    column raises there instead of quietly becoming the constant 0.0.
    """
    X = X.replace([np.inf, -np.inf], np.nan)
    all_nan = [c for c in X.columns if X[c].isna().all()]
    if all_nan:
        print(f"  WARNING: neutralising entirely-missing feature column(s) to "
              f"0.0: {all_nan} — they carry no information for the model.")
        X[all_nan] = 0.0
    return X


