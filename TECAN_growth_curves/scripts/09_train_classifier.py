def train_model(
    X: pd.DataFrame,
    y: np.ndarray,
    model_type: str = 'hgb',
    n_folds: int = 5,
    sample_weight: Optional[np.ndarray] = None,
) -> tuple:
    """Train with stratified K-fold CV. Returns (model, metrics_dict).

    ``sample_weight`` carries the lab-frequency correction (see
    :func:`lab_sample_weights`). It is applied alongside
    ``class_weight='balanced'``, which corrects the GOOD/BAD marginal but not
    the amplitude composition of the generated set.
    """
    if model_type == 'hgb':
        model = HistGradientBoostingClassifier(
            max_iter=200,
            max_depth=5,
            min_samples_leaf=5,
            learning_rate=0.1,
            class_weight='balanced',
            random_state=42,
        )
    elif model_type == 'rf':
        # RF can't handle NaN/inf, so we wrap with a pipeline that imputes
        from sklearn.pipeline import Pipeline
        from sklearn.impute import SimpleImputer
        model = Pipeline([
            ('imputer', SimpleImputer(strategy='median')),
            ('clf', RandomForestClassifier(
                n_estimators=200,
                max_depth=8,
                min_samples_leaf=3,
                class_weight='balanced_subsample',
                random_state=42,
            )),
        ])
    else:
        raise ValueError(f"Unknown model type: {model_type}")

    # HistGradientBoosting handles NaN natively; the RF pipeline imputes.
    # Entirely-missing columns are neutralised (see clean_feature_matrix).
    X = clean_feature_matrix(X)

    # Cross-validation
    cv = StratifiedKFold(n_splits=n_folds, shuffle=True, random_state=42)
    scoring = {
        'accuracy': 'accuracy',
        'precision': 'precision',
        'recall': 'recall',
        'f1': 'f1',
        'specificity': specificity_scorer,
    }

    fit_params = {}
    if sample_weight is not None:
        weight_key = 'clf__sample_weight' if hasattr(model, 'named_steps') else 'sample_weight'
        fit_params[weight_key] = np.asarray(sample_weight, dtype=float)

    cv_results = cross_validate(
        model, X, y, cv=cv, scoring=scoring, return_train_score=False,
        params=fit_params or None,
    )

    metrics = {
        k: float(np.mean(cv_results[f'test_{k}']))
        for k in scoring
    }
    metrics_std = {
        f'{k}_std': float(np.std(cv_results[f'test_{k}']))
        for k in scoring
    }
    metrics.update(metrics_std)

    # Train final model on all data
    model.fit(X, y, **fit_params)

    # Feature importance (works for HGB, RF; Pipeline needs .named_steps access)
    fi = None
    if hasattr(model, 'feature_importances_'):
        fi = model.feature_importances_
    elif hasattr(model, 'named_steps') and hasattr(model.named_steps.get('clf', None), 'feature_importances_'):
        fi = model.named_steps['clf'].feature_importances_
    if fi is not None:
        importances = dict(zip(X.columns, fi))
        metrics['feature_importance'] = dict(
            sorted(importances.items(), key=lambda x: -x[1])
        )

    return model, metrics


def analyze_borderline(model, X, y, good_thresh=0.7, bad_thresh=0.3):
    """Analyze three-class distribution at given thresholds."""
    probs = model.predict_proba(X)[:, 1]

    good_mask = probs >= good_thresh
    bad_mask = probs <= bad_thresh
    borderline_mask = ~good_mask & ~bad_mask

    n_good = good_mask.sum()
    n_bad = bad_mask.sum()
    n_border = borderline_mask.sum()

    # Accuracy treating borderline as BAD (conservative)
    y_pred_conservative = good_mask.astype(int)
    acc = accuracy_score(y, y_pred_conservative)

    # What's in borderline?
    border_true_good = (y[borderline_mask] == 1).sum()
    border_true_bad = (y[borderline_mask] == 0).sum()

    return {
        'good_threshold': good_thresh,
        'bad_threshold': bad_thresh,
        'n_good': int(n_good),
        'n_borderline': int(n_border),
        'n_bad': int(n_bad),
        'borderline_true_good': int(border_true_good),
        'borderline_true_bad': int(border_true_bad),
        'accuracy_conservative': float(acc),
    }


