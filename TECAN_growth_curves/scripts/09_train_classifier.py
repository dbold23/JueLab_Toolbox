def load_training_data(
    ground_truth_csv: str,
    processing_results_csv: str,
) -> pd.DataFrame:
    """Merge ground truth labels with pipeline-extracted features.

    ground_truth.csv carries its own delta_od / max_od / initial_od columns.
    Merging with pandas' default suffixes renames the *pipeline's* copies
    ('delta_od' -> 'delta_od_pr'), leaving those features NaN for every
    synthetic row — missingness that identifies the data source. The
    ground-truth copies are renamed 'gt_*' instead so feature columns keep
    their names.
    """
    gt = pd.read_csv(ground_truth_csv)
    pr = pd.read_csv(processing_results_csv)

    # Standardize strain matching
    gt['strain_match'] = gt['strain_name'].str.upper().str.strip()
    pr['strain_match'] = pr['strain'].str.upper().str.strip().apply(
        lambda s: m.group(1) if (m := re.search(r'(CURVE\d+)', s)) else s
    )

    overlap = [c for c in gt.columns if c in pr.columns and c != 'strain_match']
    if overlap:
        gt = gt.rename(columns={c: f'gt_{c}' for c in overlap})

    merged = gt.merge(pr, on='strain_match', how='inner')
    merged['label'] = (merged['expected_class'] == 'GOOD').astype(int)
    merged['fit_attempted'] = fit_attempted_mask(merged)

    n_matched = len(merged)
    merged, n_dropped_scoring = drop_unscorable_rows(merged)

    n_fit = int(merged['fit_attempted'].sum())
    print(f"Loaded {n_matched} matched curves "
          f"({merged['label'].sum()} GOOD, {(~merged['label'].astype(bool)).sum()} BAD"
          + (f"; {n_dropped_scoring} dropped as not scorable" if n_dropped_scoring else "")
          + ")")
    print(f"  Fitted: {n_fit} curves carry post-fit features "
          f"({len(merged) - n_fit} rejected before fitting)")

    return merged


#: Scoring modes whose curves must never enter the training set as label 0.
#: 'a_not_identifiable' marks a curve whose asymptote A is not identifiable from
#: the window the pipeline sees, so the pipeline declining to certify it is
#: correct behaviour, not a mistake: training on it as BAD teaches the model to
#: reproduce a truncation artefact.
UNTRAINABLE_SCORING_MODES = ('a_not_identifiable',)


def _truth_column(df: pd.DataFrame, name: str) -> Optional[str]:
    """Ground-truth column name after the 'gt_' collision rename, or None."""
    for candidate in (name, f'gt_{name}'):
        if candidate in df.columns:
            return candidate
    return None


def drop_unscorable_rows(merged: pd.DataFrame) -> tuple:
    """Remove rows whose scoring_mode says they carry no learnable label.

    Ground truth v1 has no scoring_mode column; then nothing is dropped and the
    caller is told so.
    """
    col = _truth_column(merged, 'scoring_mode')
    if col is None:
        return merged, 0
    modes = merged[col].astype(str).str.strip()
    drop = modes.isin(UNTRAINABLE_SCORING_MODES)
    if not drop.any():
        return merged, 0
    counts = modes[drop].value_counts().to_dict()
    print(f"  Dropping {int(drop.sum())} curves whose scoring_mode is not "
          f"trainable: {counts}")
    return merged[~drop].reset_index(drop=True), int(drop.sum())


#: Columns of the v1 (pre-audit) ground_truth.csv -- the committed file. A
