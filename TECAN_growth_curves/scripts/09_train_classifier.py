def specificity_score(y_true, y_pred):
    """Specificity = TN / (TN + FP)."""
    tn = np.sum((y_true == 0) & (y_pred == 0))
    fp = np.sum((y_true == 0) & (y_pred == 1))
    return tn / (tn + fp) if (tn + fp) > 0 else 0.0


specificity_scorer = make_scorer(specificity_score)


