def _truth_module():
    """Import synthetic_data/src/truth.py, or None when the tree predates it.

    Repo convention: put ``synthetic_data/`` on sys.path and import ``src.*``
    (there is no top-level ``synthetic_data`` package).
    """
    synth = REPO_ROOT / 'synthetic_data'
    if not (synth / 'src' / 'truth.py').exists():
        return None
    if str(synth) not in sys.path:
        sys.path.insert(0, str(synth))
    try:
        from src import truth as truth_mod  # type: ignore
    except Exception:  # pragma: no cover - a broken truth.py must not stop training
        return None
    return truth_mod


def detect_truth_schema_version(columns) -> tuple:
    """(version, how_it_was_determined) for a ground-truth column set.

    The schema declaration lives in :mod:`synthetic_data.src.truth`, not in a
    per-row column (Contract B's 48 columns carry ``label_rule_version`` but no
    ``truth_schema_version``: it is a property of the file, not of a curve), so
    a v2 file is recognised by matching the declared column set and is then
    stamped with ``truth.TRUTH_SCHEMA_VERSION``. Only a column set that matches
    neither schema is reported as unknown.
    """
    cols = set(columns)
    if 'truth_schema_version' in cols:
        return None, 'column'          # caller reads the column itself
    truth_mod = _truth_module()
    if truth_mod is not None:
        declared = set(getattr(truth_mod, 'GROUND_TRUTH_COLUMNS', ()))
        if declared and declared <= cols:
            return (
                str(truth_mod.TRUTH_SCHEMA_VERSION),
                'src/truth.py TRUTH_SCHEMA_VERSION (all GROUND_TRUTH_COLUMNS present)',
            )
    if set(V1_GROUND_TRUTH_COLUMNS) <= cols:
        return '1', 'v1 column set (no v2 columns, no version column)'
    return 'unknown', 'column set matches neither the v1 nor the declared v2 schema'


def truth_provenance(ground_truth_csv: str) -> dict:
    """Label-rule / schema provenance of a ground_truth.csv.

    A model's predictions are only meaningful against the label rule that
    produced its training labels, so the rule version travels with the model.
    ``label_rule_version`` is a ground-truth column from v2 on;
    ``truth_schema_version`` never is, and is resolved from the declared schema
    in ``synthetic_data/src/truth.py`` (see
    :func:`detect_truth_schema_version`). Both record how they were determined
    in ``*_source`` so an inferred value is never mistaken for a stated one.
    """
    info = {
        'ground_truth': str(ground_truth_csv),
        'ground_truth_sha256': _sha256_file(ground_truth_csv),
        'label_rule': None,
        'label_rule_version': None,
        'label_rule_version_source': 'unreadable ground truth',
        'truth_schema_version': None,
        'truth_schema_version_source': 'unreadable ground truth',
        'scoring_modes': None,
    }
    try:
        gt = pd.read_csv(ground_truth_csv)
    except Exception:
        return info

    def _one(col):
        if col not in gt.columns:
            return None
        values = sorted(set(gt[col].dropna().astype(str)))
        if not values:
            return None
        return values[0] if len(values) == 1 else values

    info['label_rule'] = _one('label_rule')
    info['label_rule_version'] = _one('label_rule_version')
    if 'scoring_mode' in gt.columns:
        info['scoring_modes'] = {
            str(k): int(v) for k, v in gt['scoring_mode'].value_counts().items()
        }

    version, source = detect_truth_schema_version(gt.columns)
    if source == 'column':
        version = _one('truth_schema_version')
    info['truth_schema_version'] = version
    info['truth_schema_version_source'] = source

    if info['label_rule_version'] is not None:
        info['label_rule_version_source'] = 'label_rule_version column'
    else:
        # v1 ground truth: no column, and labels are scenario-level by
        # construction. Version 0 names that pre-rule state.
        info['label_rule_version'] = '0'
        info['label_rule_version_source'] = (
            'inferred: v1 ground truth has no label_rule_version column; '
            'labels are scenario-level'
        )
    return info


def fit_attempted_mask(df: pd.DataFrame) -> pd.Series:
    """True where the pipeline produced a Gompertz fit for the curve.

    Rows without a fit (rejected before fitting, or the fit failed) have NaN for
    every post-fit feature; training the post-fit classifier on them teaches it
    "features present -> GOOD" instead of anything about fit quality.
    """
    if 'fit_r_squared' in df.columns:
        return df['fit_r_squared'].notna()
    return pd.Series(True, index=df.index)


# ---------------------------------------------------------------------------
# Label-agreement guard
# ---------------------------------------------------------------------------

#: Scenarios smaller than this are reported but never dropped: a 1-NN estimate
#: over a handful of curves is noise.
MIN_SCENARIO_SIZE_FOR_GUARD = 5

#: Never let the guard strip the training set below this, or below two classes.
MIN_ROWS_AFTER_GUARD = 20


def _standardised_matrix(X: pd.DataFrame) -> tuple:
    """Median-imputed, z-scored copy of X with constant columns dropped."""
    Z = X.replace([np.inf, -np.inf], np.nan).astype(float)
    keep = [c for c in Z.columns if Z[c].notna().any() and Z[c].nunique(dropna=True) > 1]
    Z = Z[keep]
    if Z.shape[1] == 0:
        return Z, keep
    Z = Z.fillna(Z.median(numeric_only=True))
    Z = Z.fillna(0.0)
    sd = Z.std(ddof=0).replace(0.0, 1.0)
    return (Z - Z.mean()) / sd, keep


def label_agreement_report(
    df: pd.DataFrame,
    feature_names: Optional[Sequence[str]] = None,
    min_scenario_size: int = MIN_SCENARIO_SIZE_FOR_GUARD,
) -> dict:
    """Per-scenario 1-NN label agreement against that scenario's own baseline.

    For every fitted curve, find its nearest neighbour in the standardised
    post-fit feature space (leave-one-out, so never itself) and ask whether that
    neighbour carries the same label. A scenario whose curves sit among
    opposite-label curves is unlearnable *at the decision boundary*: the
    classifier can only memorise it.

    The comparison is NOT a flat cut. A flat 60 % would spuriously trip every
    15-curve BAD scenario in a 72 %-GOOD set, where a randomly drawn neighbour
    already agrees only ~28 % of the time. The baseline is instead the rate at
    which a neighbour drawn at random from the rest of the frame would carry the
    curve's own label -- i.e. the prevalence of that scenario's own class in the
    remainder. A scenario is flagged only when its measured agreement fails to
    beat that.

    Returns a dict with per-scenario rows and the list of flagged scenarios.
    """
    from sklearn.neighbors import NearestNeighbors

    fitted = df[df['fit_attempted']].reset_index(drop=True) if 'fit_attempted' in df.columns else df.reset_index(drop=True)
    scen_col = _truth_column(fitted, 'scenario')
    report = {
        'method': (
            'leave-one-out 1-NN over the standardised post-fit feature matrix; '
            'baseline = P(a random other curve carries this curve\'s label)'
        ),
        'n_rows': int(len(fitted)),
        'min_scenario_size': int(min_scenario_size),
        'scenarios': [],
        'flagged_scenarios': [],
        'skipped': None,
    }
    if scen_col is None:
        report['skipped'] = 'no scenario column in the merged frame'
        return report
    if len(fitted) < 4 or fitted['label'].nunique() < 2:
        report['skipped'] = 'fewer than 4 rows, or a single class'
        return report

    X, _ = prepare_postfit_features(fitted, feature_names=feature_names)
    Z, used = _standardised_matrix(X)
    if Z.shape[1] == 0:
        report['skipped'] = 'no non-constant post-fit feature to measure over'
        return report
    report['features_used'] = list(used)

    y = fitted['label'].values.astype(int)
    nn = NearestNeighbors(n_neighbors=2).fit(Z.values)
    _, idx = nn.kneighbors(Z.values)
    # column 0 is the point itself (distance 0) unless there are exact ties
    neighbour = np.where(idx[:, 0] == np.arange(len(idx)), idx[:, 1], idx[:, 0])
    agrees = (y[neighbour] == y)

    scenarios = fitted[scen_col].astype(str).values
    for name in sorted(set(scenarios)):
        mask = scenarios == name
        n = int(mask.sum())
        rest = ~mask
        if rest.sum() == 0:
            continue
        # Baseline: chance that a curve drawn from the rest of the frame shares
        # this curve's label, averaged over the scenario's curves.
        p_rest_good = float((y[rest] == 1).mean())
        baseline = float(np.mean(np.where(y[mask] == 1, p_rest_good, 1.0 - p_rest_good)))
        agreement = float(agrees[mask].mean())
        majority = float(max((y[mask] == 1).mean(), (y[mask] == 0).mean()))
        row = {
            'scenario': name,
            'n': n,
            'agreement': agreement,
            'baseline': baseline,
            'majority_class_rate': majority,
            'label_good_fraction': float((y[mask] == 1).mean()),
            'beats_baseline': bool(agreement > baseline),
            'judged': bool(n >= min_scenario_size),
        }
        report['scenarios'].append(row)
        if row['judged'] and not row['beats_baseline']:
            report['flagged_scenarios'].append(name)

    return report


def apply_label_agreement_guard(
    df: pd.DataFrame,
    report: dict,
    enabled: bool = True,
) -> tuple:
    """Drop flagged scenarios from a training frame, with a safety valve.

    Returns ``(kept_df, decision)``. The guard never leaves fewer than
    MIN_ROWS_AFTER_GUARD rows or a single class behind: in that case it warns
    and drops nothing, because a training set that small is a worse problem than
    an unlearnable scenario.
    """
    decision = {
        'enabled': bool(enabled),
        'flagged_scenarios': list(report.get('flagged_scenarios', [])),
        'dropped_scenarios': [],
        'n_rows_dropped': 0,
        'override': None,
    }
    flagged = decision['flagged_scenarios']
    if not enabled:
        decision['override'] = 'guard disabled (--no-label-agreement-guard)'
        if flagged:
            print(f"  Label-agreement guard DISABLED; would have dropped: {flagged}")
        return df, decision
    if not flagged:
        return df, decision

    scen_col = _truth_column(df, 'scenario')
    if scen_col is None:
        decision['override'] = 'no scenario column'
        return df, decision

    keep = ~df[scen_col].astype(str).isin(flagged)
    kept = df[keep].reset_index(drop=True)
    if len(kept) < MIN_ROWS_AFTER_GUARD or kept['label'].nunique() < 2:
        decision['override'] = (
            f"dropping {flagged} would leave {len(kept)} rows / "
            f"{kept['label'].nunique()} classes — kept them instead"
        )
        print(f"  WARNING: label-agreement guard NOT applied: {decision['override']}")
        return df, decision

    decision['dropped_scenarios'] = list(flagged)
    decision['n_rows_dropped'] = int((~keep).sum())
    print(f"  Label-agreement guard drops {decision['n_rows_dropped']} rows from "
          f"{flagged}: their 1-NN label agreement does not beat the rate a "
          f"random neighbour would already achieve.")
    return kept, decision


# Fit columns the audit CSV snapshotted at audit time. They collide with the
# current processing_results columns of the same name, so they are dropped
# before merging rather than shadowing the live features.
AUDIT_SNAPSHOT_COLUMNS = ('r_squared', 'gompertz_a', 'gompertz_mu', 'gompertz_lambda')


def load_real_audit_data(audit_csv: str, results_dir: str) -> pd.DataFrame:
    """Load the manual real-data audit as labelled examples.

    Labels come from the audit itself: 'is_good' is the verdict the auditor was
    shown, and audit_result says whether that verdict was 'correct' (keep it),
    'wrong' (flip it) or 'unsure' (drop the curve).

    The audit CSV also carries is_good / r_squared / gompertz_* snapshots that
    collide with the current processing_results columns. Merging with suffixes
    made the code read the CURRENT pipeline verdict ('is_good_pr') instead of
    the audited one — inverting every curve the pipeline has since changed its
    mind about — and renamed gompertz_a/mu/lambda away, leaving them NaN for
    every real row. So the snapshot columns are dropped and the audited verdict
    is renamed before the merge.

    Returns a DataFrame in the same shape as load_training_data output, with a
    'label' column and the pipeline's post-fit feature columns intact.
    """
    audit = pd.read_csv(audit_csv)

    # Load all group results
    results_base = Path(results_dir)
    all_results = []
    for group_dir in sorted(results_base.glob('Group*_Results')):
        csv_path = group_dir / 'processing_results.csv'
        if csv_path.exists():
            df = pd.read_csv(csv_path)
            all_results.append(df)
    if not all_results:
        consolidated = results_base / 'all_groups_results.csv'
        if consolidated.exists():
            all_results.append(pd.read_csv(consolidated))
    if not all_results:
        return pd.DataFrame()

    real_df = pd.concat(all_results, ignore_index=True)
    real_df['strain_match'] = real_df['strain'].str.strip()

    audit['strain_match'] = audit['strain'].str.strip()
    audit = audit.drop(columns=[c for c in AUDIT_SNAPSHOT_COLUMNS if c in audit.columns])
    audit = audit.rename(columns={
        'is_good': 'audited_is_good',
        'classification_reason': 'audited_classification_reason',
        'strain': 'audited_strain',
    })

    merged = audit.merge(real_df, on='strain_match', how='inner')
    if len(merged) == 0:
        return pd.DataFrame()

    # Keep only curves the auditor actually decided on
    verdict = merged['audit_result'].astype(str).str.strip().str.lower()
    decided = verdict.isin({'correct', 'wrong'})
    if not decided.all():
        counts = verdict[~decided].value_counts().to_dict()
        print(f"  Dropping {int((~decided).sum())} undecided audit curves: {counts}")
        merged = merged[decided].reset_index(drop=True)
        verdict = verdict[decided].reset_index(drop=True)

    # True label: the audited verdict, flipped where the auditor called it wrong
    audited_good = _as_bool(merged['audited_is_good'])
    merged['label'] = (audited_good == (verdict == 'correct')).astype(int)
    merged['fit_attempted'] = fit_attempted_mask(merged)

    # Use real strain name for metadata
    if 'strain' not in merged.columns:
        merged['strain'] = merged['strain_match']

    n_good = int(merged['label'].sum())
    n_bad = int((merged['label'] == 0).sum())
    print(f"  Real audit data: {len(merged)} curves ({n_good} GOOD, {n_bad} BAD)")

    return merged


def prepare_prefit_features(df: pd.DataFrame, raw_data_dir: str = None) -> tuple:
    """Extract pre-fit features from raw data files (not post-pipeline CSV).

    If raw_data_dir is provided, reads actual raw OD data and computes features
    using extract_prefit_features(). This ensures training features match
    inference features exactly — no train/inference mismatch.

    Falls back to CSV-proxy extraction if raw_data_dir is not available.
    """
    y = df['label'].values

    if raw_data_dir is not None:
        raw_dir = Path(raw_data_dir)
        data_files = sorted(raw_dir.glob('*.csv'))
        if not data_files:
            print(f"  Warning: no CSV files found in {raw_dir}, falling back to CSV proxy")
            return _prepare_prefit_from_csv(df)

        # Build lookup: strain_name → (time, od) from raw data
        print(f"  Extracting pre-fit features from {len(data_files)} raw data files...")
        raw_curves = {}
        for fpath in data_files:
            raw_df = pd.read_csv(fpath)
            time_col = [c for c in raw_df.columns if 'TIME' in c.upper()][0]
            time = raw_df[time_col].values
            for col in raw_df.columns:
                if col == time_col:
                    continue
                # Extract curve name: e.g. "SYNTHETIC_400pts_99h_CURVE0005_blanked" → "CURVE0005"
                import re as _re
                m = _re.search(r'(CURVE\d+)', col)
                if m:
                    curve_name = m.group(1)
                    od = raw_df[col].values
                    # Remove NaN values
                    valid = ~np.isnan(od)
                    if valid.sum() > 5:
                        raw_curves[curve_name] = (time[valid], od[valid])

        print(f"  Found {len(raw_curves)} curves in raw data")

        # Extract features for each training curve
        rows = []
        matched = 0
        for _, row_data in df.iterrows():
            strain = row_data.get('strain_match', '')
            # Try matching
            import re as _re
            m = _re.search(r'(CURVE\d+)', str(strain))
            curve_key = m.group(1) if m else strain

            if curve_key in raw_curves:
                t, od = raw_curves[curve_key]
                # Pass strain name for metadata extraction (synthetic names
                # like CURVE0005 won't match control patterns → NaN metadata)
                original_strain = row_data.get('strain_name', row_data.get('strain', ''))
                features = extract_prefit_features(t, od, strain_name=str(original_strain))
                rows.append(features)
                matched += 1
            else:
                # Missing curve — fill with NaN
                rows.append({f: np.nan for f in PREFIT_FEATURES})

        print(f"  Matched {matched}/{len(df)} curves to raw data")

        X = pd.DataFrame(rows)[PREFIT_FEATURES]
        return X, y

    return _prepare_prefit_from_csv(df)


def _prepare_prefit_from_csv(df: pd.DataFrame) -> tuple:
    """Fallback: extract pre-fit features from CSV columns (proxy, not ideal)."""
    print("  WARNING: Using CSV-proxy features (post-pipeline values).")
    print("  Pass --raw-data-dir for honest pre-fit features.")
    feature_map = {
        'raw_delta_od': 'delta_od',
        'raw_max_od': 'max_od',
        'raw_snr': 'snr',
        'raw_monotone_fraction': 'monotone_fraction',
        'raw_baseline_std': 'baseline_std',
        'raw_baseline_mean': None,
        'n_points': 'points_used',
        'time_span': 'truncation_time',
    }

    X = pd.DataFrame()
    for feat, col in feature_map.items():
        if col and col in df.columns:
            X[feat] = df[col].astype(float)
        else:
            X[feat] = np.nan

    if 'initial_od' in df.columns:
        X['raw_baseline_mean'] = df['initial_od'].astype(float)

    # No metadata columns: is_control / concentration_numeric are not model
    # features (see ml_classifier.METADATA_FEATURES).
    y = df['label'].values
    return X[[f for f in PREFIT_FEATURES if f in X.columns]], y


def prepare_postfit_features(
    df: pd.DataFrame,
    feature_names: Optional[Sequence[str]] = None,
) -> tuple:
    """Extract post-fit feature matrix and labels from merged data.

    ``feature_names`` defaults to ALL_POSTFIT_FEATURES. It is passed explicitly
    when scoring a previously shipped model whose feature_config.json lists a
    different set (e.g. one that still carries the metadata columns), so the old
    and the new model can be compared on the same rows.
    """
    names = list(feature_names) if feature_names else list(ALL_POSTFIT_FEATURES)
    X = pd.DataFrame(index=df.index)

    # Direct and secondary features from CSV
    for feat in names:
        if feat in df.columns:
            X[feat] = df[feat].astype(float)
        else:
            X[feat] = np.nan

    # Compute derived features row by row
    derived_cols = [c for c in ('mu_over_a', 'lambda_over_trunc_time',
                                'rmse_over_delta_od', 'err_product',
                                'points_per_hour') if c in names]
    if derived_cols and not all(X[c].notna().any() for c in derived_cols):
        derived_rows = []
        for _, row in X.iterrows():
            derived_rows.append(compute_derived_features(row.to_dict()))
        derived_df = pd.DataFrame(derived_rows, index=X.index)
        for col in derived_cols:
            X[col] = derived_df[col].values

    # Metadata columns are only filled when a legacy model asks for them; they
    # are not part of ALL_POSTFIT_FEATURES any more (M27).
    wanted_meta = [f for f in METADATA_FEATURES if f in names]
    if wanted_meta:
        strain_col = 'strain' if 'strain' in df.columns else 'strain_name'
        if strain_col in df.columns:
            for pos, strain in enumerate(df[strain_col]):
                meta = extract_metadata_features(str(strain))
                for feat in wanted_meta:
                    X.loc[X.index[pos], feat] = meta[feat]

    y = df['label'].values
    return X[names].reset_index(drop=True), y


