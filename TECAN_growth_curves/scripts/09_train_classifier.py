"""
Train ML classifiers for growth curve quality classification.

Trains two models:
  1. Pre-fit gate: rejects obvious junk before expensive fitting
  2. Post-fit classifier: three-class (GOOD/BORDERLINE/BAD) after Gompertz fit

Training features are generated by this script: it runs
01_growth_curve_analysis.py over the synthetic curves WITHOUT --ml-classify, so
every curve gets the same chance to be fitted. The models are trained on
synthetic data only; the manual real-data audit is held out as an external test
set.

Usage:
    python 09_train_classifier.py                     # Train on synthetic data
    python 09_train_classifier.py --compare            # Compare GBT vs RF
    python 09_train_classifier.py --validate-real      # Report external real-data metrics
    python 09_train_classifier.py --output models/     # Custom output directory
"""

