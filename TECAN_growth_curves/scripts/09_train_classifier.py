DEFAULT_LAB_PRIOR = 'synthetic_data/config/lab_prior.json'


def _band_of(delta_od: float, bands: Sequence[dict]) -> Optional[str]:
    """Name of the lab_prior band a delta_od falls in."""
    if delta_od is None or not np.isfinite(delta_od):
        return None
    for band in bands:
        lo = band.get('delta_od_min')
        hi = band.get('delta_od_max')
        lo = -np.inf if lo is None else float(lo)
        hi = np.inf if hi is None else float(hi)
        if lo <= delta_od < hi:
            return band['name']
    return bands[-1]['name'] if bands else None


def lab_sample_weights(df: pd.DataFrame, lab_prior_path) -> tuple:
    """Per-sample weights that re-weight the generated set to lab frequencies.

    Generation stays broad on purpose: with ~1000 curves, cutting the borderline
    scenarios down to their lab frequency starves exactly the region where the
    classifier decides. So the *composition* is corrected at fit time instead --
    every curve keeps its gradient, scaled by how common its amplitude band is
    on the real plates.

    weight_i = P_lab(band_i) / P_generated(band_i), normalised to mean 1.
    Returns ``(weights, info)``; weights is None when no prior is available.
    """
    info = {'lab_prior': str(lab_prior_path), 'applied': False, 'reason': None}
    try:
        with open(lab_prior_path) as fh:
            prior = json.load(fh)
    except (OSError, ValueError) as exc:
        info['reason'] = f'lab prior unreadable ({exc.__class__.__name__})'
        return None, info

    bands = prior.get('bands') or []
    if not bands:
        info['reason'] = 'lab prior carries no bands'
        return None, info

    band_col = _truth_column(df, 'lab_band')
    names = None
    if band_col is not None and df[band_col].notna().any():
        names = df[band_col].astype(str)
        info['band_source'] = f'ground truth column {band_col}'
    else:
        delta_col = _truth_column(df, 'delta_od')
        if delta_col is None:
            info['reason'] = 'no lab_band and no delta_od column to band on'
            return None, info
        deltas = pd.to_numeric(df[delta_col], errors='coerce')
        names = deltas.apply(lambda d: _band_of(d, bands))
        info['band_source'] = f'banded from {delta_col} via lab_prior band edges'

    lab_fraction = {b['name']: float(b.get('fraction', 0.0)) for b in bands}
    counts = names.value_counts(dropna=True)
    generated_fraction = (counts / counts.sum()).to_dict()

    weights = np.ones(len(df), dtype=float)
    for pos, name in enumerate(names):
        gen = generated_fraction.get(name)
        lab = lab_fraction.get(name)
        if not gen or lab is None:
            weights[pos] = 1.0
        else:
            weights[pos] = lab / gen
    if not np.isfinite(weights).all() or weights.sum() <= 0:
        info['reason'] = 'degenerate weights'
        return None, info
    weights = weights / weights.mean()

    info['applied'] = True
    info['schema'] = prior.get('schema')
    info['lab_fraction'] = lab_fraction
    info['generated_fraction'] = {str(k): float(v) for k, v in generated_fraction.items()}
    info['weight_by_band'] = {
        str(name): float(np.mean(weights[np.asarray(names == name)]))
        for name in sorted(set(names.dropna()))
    }
    info['note'] = (
        "class_weight='balanced' corrects the GOOD/BAD marginal but not the "
        "amplitude composition; these weights correct the composition."
    )
    return weights, info


# ---------------------------------------------------------------------------
# Threshold sweep
# ---------------------------------------------------------------------------

#: Minimum lab-weighted specificity the deployed good_threshold must reach.
#: The pipeline's job is to refuse to certify bad wells, so specificity is the
#: quantity the threshold is chosen on.
TARGET_SPECIFICITY = 0.95

#: Minimum lab-weighted NPV before a curve may be called BAD outright.
TARGET_NPV = 0.90


def _weighted_counts(y_true, y_pred, w):
    tp = float(np.sum(w[(y_true == 1) & (y_pred == 1)]))
    tn = float(np.sum(w[(y_true == 0) & (y_pred == 0)]))
    fp = float(np.sum(w[(y_true == 0) & (y_pred == 1)]))
    fn = float(np.sum(w[(y_true == 1) & (y_pred == 0)]))
    return tp, tn, fp, fn


def threshold_sweep(probs, y_true, sample_weight=None, step: float = 0.05) -> dict:
    """Specificity / NPV / recall vs threshold, and the thresholds they imply.

    Reported in the model card so a reader can see what the deployed
    good_threshold and bad_threshold buy, instead of taking 0.7 / 0.3 on faith.
    """
    probs = np.asarray(probs, dtype=float)
    y_true = np.asarray(y_true, dtype=int)
    w = np.ones(len(y_true)) if sample_weight is None else np.asarray(sample_weight, dtype=float)

    rows = []
    for t in np.round(np.arange(step, 1.0, step), 4):
        pred = (probs >= t).astype(int)
        tp, tn, fp, fn = _weighted_counts(y_true, pred, w)
        rows.append({
            'threshold': float(t),
            'specificity': float(tn / (tn + fp)) if (tn + fp) > 0 else None,
            'npv': float(tn / (tn + fn)) if (tn + fn) > 0 else None,
            'precision': float(tp / (tp + fp)) if (tp + fp) > 0 else None,
            'recall': float(tp / (tp + fn)) if (tp + fn) > 0 else None,
            'n_called_good': int(np.sum(pred == 1)),
        })

    def _youden(row):
        if row['specificity'] is None or row['recall'] is None:
            return -1.0
        return row['specificity'] + row['recall'] - 1.0

    # Among the thresholds that clear the specificity target, take the one with
    # the best separation (Youden's J); ties -- which is what perfect separation
    # produces -- go to the threshold nearest 0.5, so a degenerate sweep lands
    # on the neutral operating point instead of the edge of the grid.
    eligible = [r for r in rows
                if r['specificity'] is not None and r['specificity'] >= TARGET_SPECIFICITY]
    pool = eligible or rows
    good = None
    if pool:
        good = max(
            pool,
            key=lambda r: (round(_youden(r), 6), -abs(r['threshold'] - 0.5)),
        )['threshold']

    # bad_threshold: the highest threshold still below good_threshold at which
    # everything called BAD is mostly truly BAD.
    below = [r for r in rows if good is None or r['threshold'] < good]
    ok = [r for r in below if r['npv'] is not None and r['npv'] >= TARGET_NPV]
    if ok:
        bad = max(r['threshold'] for r in ok)
    elif below:
        bad = min(r['threshold'] for r in below)
    else:
        bad = float((good or 0.6) / 2)

    return {
        'targets': {'specificity': TARGET_SPECIFICITY, 'npv': TARGET_NPV},
        'weighted': sample_weight is not None,
        'n_rows': int(len(y_true)),
        'sweep': rows,
        'good_threshold': float(good) if good is not None else None,
        'bad_threshold': float(bad),
        'degenerate': bool(len(eligible) == len(rows)),
        'policy': (
            f"good_threshold = the threshold with the best "
            f"{'lab-weighted' if sample_weight is not None else 'unweighted'} "
            f"Youden's J among those reaching the target specificity (ties to "
            f"the threshold nearest 0.5); bad_threshold = highest threshold "
            f"below it whose NPV reaches the target"
        ),
    }


